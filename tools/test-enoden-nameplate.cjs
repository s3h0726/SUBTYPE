'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');

const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const templates=read('js/station-sign-templates.js').replace(/\bexport /g,'');
const sandbox={};
vm.createContext(sandbox);
vm.runInContext(templates+';globalThis.enodenResolver=resolveStationSignTemplate',sandbox);
const route=JSON.parse(read('data/generated/routes/line-99320.json')).route;
assert.equal(route.id,'line-99320');
assert.equal(route.operatorId,'enoshimadentetsu');
assert.equal(route.stations.length,15);
assert.equal(sandbox.enodenResolver(route).style,'enoden');
assert.equal(sandbox.enodenResolver({...route,stationSignTemplate:null}).style,'enoden','operator ID must select Enoden');
assert.equal(sandbox.enodenResolver({...route,operatorId:'other',stationSignTemplate:null,operator:{ja:'江ノ島電鉄'}}).style,'enoden','Japanese operator name must select Enoden');
assert.notEqual(sandbox.enodenResolver({...route,id:'other',operatorId:'odakyu',stationSignTemplate:'odakyu'}).style,'enoden','other operators unaffected');
const yug=route.stations.find(x=>x.ja==='由比ヶ浜'),hase=route.stations.find(x=>x.ja==='長谷'),wada=route.stations.find(x=>x.ja==='和田塚');
assert.ok(yug&&hase&&wada,'photographed EN13 and neighboring stations need existing source records');

const source=read('js/game.js');
const start=source.indexOf('  applyEnodenNameplate(station,previous,next){');
const end=source.indexOf('\n  activeRoute(station)',start);
assert.ok(start>=0&&end>start,'Enoden runtime method missing');
const method=source.slice(start,end);
const selectors=['#station-sign','#station-badge','#korail-previous-badge','#korail-next-badge','#previous-station-name','#previous-station-romaji','#next-station-name','#next-station-romaji'];
const nodes=Object.fromEntries(selectors.map(x=>[x,{textContent:'',hidden:true,dataset:{}}]));
nodes['#station-sign'].dataset.signStyle='enoden';
const probeCtx={nodes};
vm.createContext(probeCtx);
vm.runInContext('class EnodenProbe { constructor(route){this.route=route} activeRoute(){return this.route} stationKoDisplay(x){return x||""} '+method+' } globalThis.EnodenProbe=EnodenProbe;globalThis.$=name=>nodes[name]',probeCtx);
const probe=new probeCtx.EnodenProbe(route);
probe.applyEnodenNameplate(yug,hase,wada);
assert.equal(nodes['#station-badge'].textContent,'13');
assert.equal(nodes['#korail-previous-badge'].textContent,'12');
assert.equal(nodes['#korail-next-badge'].textContent,'14');
assert.equal(nodes['#previous-station-name'].textContent,'長谷');
assert.equal(nodes['#next-station-name'].textContent,'和田塚');
assert.equal(nodes['#previous-station-romaji'].textContent,'Hase','photo-based Hase romanization must override MLIT auto-reading');
assert.equal(nodes['#next-station-romaji'].textContent,wada.romaji);
assert.equal(nodes['#station-badge'].hidden,false);
probe.applyEnodenNameplate(route.stations[0],null,route.stations[1]);
assert.equal(nodes['#station-badge'].textContent,'01');
assert.equal(nodes['#korail-previous-badge'].hidden,true);
probe.applyEnodenNameplate(route.stations[14],route.stations[13],null);
assert.equal(nodes['#station-badge'].textContent,'15');
assert.equal(nodes['#korail-next-badge'].hidden,true);
nodes['#station-sign'].dataset.signStyle='jr-east';
nodes['#station-badge'].textContent='unmodified';
probe.applyEnodenNameplate(yug,hase,wada);
assert.equal(nodes['#station-badge'].textContent,'unmodified','non-Enoden template must be left unchanged');

for(const snippet of ['this.applyEnodenNameplate(station,previous,following)','this.applyEnodenNameplate(station,station,next)','this.applyEnodenNameplate(station,this.currentStation(),station)'])assert.ok(source.includes(snippet),'runtime call missing: '+snippet);
const css=read('css/enoden-nameplate.css'),html=read('index.html');
assert.ok(html.includes('css/enoden-nameplate.css?v=20261105-enoden-green-en13'),'public site must load Enoden stylesheet');
assert.ok(css.includes('[data-sign-style="enoden"]'),'scope styles only to Enoden');
assert.ok(css.includes('background:#efd54c!important'),'yellow line not present');
assert.ok(css.includes('.station-badge:not([hidden])'),'center EN number badge not styled');
assert.ok(css.includes('.station-sign-input input'),'Japanese typing input must be preserved');
console.log('PASS: Enoden 15 stations, EN01–EN15, EN13 Yuigahama, direction neighbors, operator isolation, input preserved');
