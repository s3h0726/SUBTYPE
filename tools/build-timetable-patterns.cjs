'use strict';

const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const definitions = JSON.parse(fs.readFileSync(path.join(root, 'data/services/timetable-audit-jp.json'), 'utf8'));

function registerTimetablePatterns(catalog, definitions) {
  for (const entry of definitions.patterns) {
    const trainTypeId = entry.id + '-local';
    if (!catalog.trainTypes.some(type => type.id === trainTypeId)) {
      catalog.trainTypes.push({id: trainTypeId, operatorId: entry.operatorId, names: entry.names, priority: 0});
    }
    for (const [direction, officialRouteId] of Object.entries(entry.directions)) {
      const id = entry.id + '-' + direction;
      if (catalog.servicePatterns.some(pattern => pattern.id === id)) continue;
      const forward = direction === 'forward';
      const stops = forward ? [...entry.stationIds] : [...entry.stationIds].reverse();
      const origin = forward ? entry.originNames : entry.destinationNames;
      const destination = forward ? entry.destinationNames : entry.originNames;
      for (const [stationId, names] of [[stops[0], origin], [stops.at(-1), destination]]) {
        if (!catalog.destinations.some(item => item.stationId === stationId)) catalog.destinations.push({stationId, names});
      }
      const endpoints = {originStationId: stops[0], destinationStationId: stops.at(-1), originNames: origin, destinationNames: destination};
      const common = {baseRouteId: entry.routeId, trainTypeId, directionId: direction, status: 'active', ...endpoints};
      catalog.servicePatterns.push({
        ...common, id, stopStationIds: stops, names: entry.names, trimRepeatedOrigin: true, requireExactCalls: true,
        serviceClass: entry.serviceClass, calendar: entry.calendar,
        sources: [{type: 'official-gtfs', url: entry.sourceUrl, sha256: entry.sourceRevision, officialRouteId, checkedAt: entry.accessedAt}]
      });
      catalog.serviceJourneys.push({...common, id: 'journey-' + id, servicePatternId: id});
    }
  }
}

const generated = '/* Generated by tools/build-timetable-patterns.cjs. */\n' +
  '(' + registerTimetablePatterns.toString() + ')(globalThis.TRT_TOKYO_SERVICE_PATTERNS, ' +
  JSON.stringify(definitions) + ');\n';
fs.writeFileSync(path.join(root, 'js/japan-timetable-audit-patterns.js'), generated);
