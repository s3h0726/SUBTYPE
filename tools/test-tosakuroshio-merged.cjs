#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const route=JSON.parse(read('data/route-overrides/tosakuroshio-nakamura-sukumo.json')).route;
assert.equal(route.id,'line-99814');
assert.equal(route.line.ko,'나카무라·스쿠모선');
assert.equal(route.stations.length,22);
assert.equal(route.directedSegments.length,21);
assert.equal(route.geometry.length,583);
assert.equal(route.stations.filter(st=>st.ja==='中村').length,1);
assert.equal(route.stations[0].ja,'窪川');
assert.equal(route.stations[14].ja,'中村');
assert.equal(route.stations.at(-1).ja,'宿毛');
assert.deepEqual(route.services.map(s=>s.stops.length),[22,15,8]);
for(const seg of route.directedSegments)assert.ok(seg.geometry.length>2);
const indexSource=read('js/japan-lite-index.js');
const lite=JSON.parse(indexSource.slice(indexSource.indexOf('=')+1,indexSource.lastIndexOf(';')));
const sandbox={TRT_JAPAN_LITE_INDEX:lite,console:{error:message=>{throw Error(message)}}};
vm.createContext(sandbox);
vm.runInContext(read('js/tosakuroshio-nakamura-sukumo-patch.js'),sandbox);
const parent=lite.routes.find(r=>r.id==='line-99814');
const old=lite.routes.find(r=>r.id==='line-99815');
assert.equal(parent.stationCount,22);
assert.equal(parent.line.ko,'나카무라·스쿠모선');
assert.ok(parent.lazySource.includes('tosakuroshio-nakamura-sukumo.json'));
assert.equal(old.visibility,'internal');
assert.equal(old.playable,false);
assert.equal(old.parentLineId,parent.id);
assert.equal(lite.routes.filter(r=>r.id==='line-99814'&&r.visibility!=='internal').length,1);
const displaySource=read('index.html');
assert.ok(displaySource.includes('tosakuroshio-nakamura-sukumo-patch.js'),'Browser patch must be loaded');
assert.ok(read('data/editor-overrides.json').includes('"ko": "나카무라·스쿠모선"'),'Name editor must not revert the merged line name');
assert.ok(read('js/feature-flags.js').includes("'line-99815':'line-99814'"),'Historical records should resolve to merged card');
console.log('PASS: single line card and continuous 22-station playable route');
