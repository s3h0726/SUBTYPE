#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const pkg=JSON.parse(read('package.json'));
const version=pkg.appVersion;
assert.match(pkg.version,/^\d+\.\d+\.\d+$/,'npm package version must remain MAJOR.MINOR.PATCH');
assert.match(version,/^\d+\.\d+\.\d+\.\d+$/,'App version must use MAJOR.MINOR.PATCH.REVISION');
assert.equal(pkg.version,version.split('.').slice(0,3).join('.'),'npm version must match first three app-version components');
const html=read('index.html'),labels=[...html.matchAll(/<(?:span|strong)\b[^>]*\bdata-app-version\b[^>]*>([^<]*)<\/(?:span|strong)>/g)].map(m=>m[1].trim());
assert.equal(labels.length,4,'home, topbar, home footer and settings must display the version');
assert(labels.every(label=>label==='v'+version),'All visible version labels must match package.json appVersion');
assert(html.includes('<meta name="application-version" content="'+version+'">'),'Application version meta tag mismatch');
assert(html.includes('./css/app-version.css?v='+version),'Version stylesheet cache key mismatch');
assert(read('CHANGELOG.md').includes('## [v'+version+']'),'Changelog must contain the current version');
assert(read('README.md').includes('**현재 버전: v'+version+' (개발 중)**'),'README version banner mismatch');
const script=read('tools/build-app-bundle.js');
assert(script.includes("const appVersion=JSON.parse(read('package.json')).appVersion"),'Bundle build must source appVersion from package.json');
console.log('PASS: SUBTYPE v'+version+' matched package.json, HTML, CSS and changelog');
