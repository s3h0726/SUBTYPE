'use strict';
// Only append the two independently source-linked school-day services.
// Do not regenerate the Hong Kong physical network or unrelated routes.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const write=(p,text)=>{const full=path.join(root,p);fs.mkdirSync(path.dirname(full),{recursive:true});if(!fs.existsSync(full)||fs.readFileSync(full,'utf8')!==text)fs.writeFileSync(full,text)};
const writeJson=(p,obj)=>write(p,JSON.stringify(obj,null,2)+'\n');
const {SPECS,extraHongKongLightRailRoutes}=require('./lib/hk-school-special-routes.cjs');
const preview=process.argv.includes('--validation-preview'),ids=new Set(SPECS.map(s=>s.id));
const indexPath='data/hk/generated/index.json',index=read(indexPath);
const original=index.routes.filter(route=>!ids.has(route.id));
assert.equal(SPECS.length,2);
assert(!original.some(route=>/voyager/i.test(route.id)),'Do not add Voyager routes');
const sources=original.filter(route=>route.category==='light_rail'&&route.geometryReady===true)
 .map(route=>read(route.lazySource));
const extras=extraHongKongLightRailRoutes(sources,{validationPreview:preview,gameplayReview:read('data/hk/master/gameplay-review.json')});
for(const route of extras){
 assert(ids.has(route.id));
 assert.equal(route.stations.length-1,route.directedSegments.length);
 writeJson('data/hk/generated/routes/'+route.id+'.json',route);
}
const meta=extras.map(route=>{
 const {geometry,directedSegments,stations,...rest}=route;
 return{...rest,lazy:true,lazySource:'data/hk/generated/routes/'+route.id+'.json',
  stationCount:stations.length,stationSequence:stations.map(s=>s.id),
  searchStations:stations.flatMap(s=>[s.ja,s.romaji,s.ko]).filter(Boolean)};
});
index.routes=[...original,...meta];
index.audit={...index.audit,totalServices:index.routes.length,
 playableServices:index.routes.filter(route=>route.playable&&route.releaseStatus==='ready').length};
writeJson(indexPath,index);
write('js/hong-kong-index-data.js',
 '/* AUTO-GENERATED by tools/build-hk-data.cjs. */\nwindow.TRT_HONG_KONG_INDEX='+JSON.stringify(index)+';\n');
let html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const asset='js/hong-kong-index-data.js';
const hash=crypto.createHash('sha256').update(fs.readFileSync(path.join(root,asset))).digest('hex').slice(0,12);
html=html.replace(/\.\/js\/hong-kong-index-data\.js(?:\?v=[^"']*)?/g,'./js/hong-kong-index-data.js?v='+hash);
write('index.html',html);
console.log(JSON.stringify({specials:extras.map(r=>({id:r.id,stops:r.stations.length,status:r.releaseStatus})),
  totalPublishedRoutes:index.routes.length,playablePublishedRoutes:index.audit.playableServices,preview},null,2));
